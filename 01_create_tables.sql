//table creation
SET SERVEROUTPUT ON;

CREATE TABLE patients (
    patient_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR2(50) NOT NULL,
    last_name        VARCHAR2(50) NOT NULL,
    date_of_birth    DATE,
    gender           VARCHAR2(20) CHECK (gender IN ('Female', 'Male', 'Other')),
    phone            VARCHAR2(20),
    email            VARCHAR2(100) UNIQUE,
    created_at       DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE doctors (
    doctor_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR2(50) NOT NULL,
    last_name        VARCHAR2(50) NOT NULL,
    specialty        VARCHAR2(80) NOT NULL,
    phone            VARCHAR2(20),
    email            VARCHAR2(100) UNIQUE,
    created_at       DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE appointments (
    appointment_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id             NUMBER NOT NULL REFERENCES patients(patient_id),
    doctor_id              NUMBER NOT NULL REFERENCES doctors(doctor_id),
    appointment_datetime  TIMESTAMP NOT NULL,
    reason                 VARCHAR2(250) NOT NULL,
    status                 VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL
                           CHECK (status IN ('SCHEDULED', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    created_at             DATE DEFAULT SYSDATE NOT NULL,
    UNIQUE (doctor_id, appointment_datetime),
    UNIQUE (patient_id, appointment_datetime)
);


